"""Bakes the pixel font (Jersey 10, SIL OFL, art_source/fonts) into two sprite atlases and writes the GML that
draws with them (tools/gml/scr_font.gml). GameMaker's own font assets can only bake from installed system fonts and
blur when scaled, so the game draws text itself from these atlases: whole pixels, proportional spacing, and
vertical centring on the capital letters.   Run:  python tools/build_font.py"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, os.path.dirname(__file__))
from gm_sprite import write_sprite, ROOT

TTF = os.path.join(ROOT, "art_source", "fonts", "Jersey10-Regular.ttf")
FIRST, LAST = 32, 126
COLS = 16


def bake(name, size):
    ft = ImageFont.truetype(TTF, size)
    asc, desc = ft.getmetrics()
    top = ft.getbbox("H")[1]
    cap = ft.getbbox("H")[3] - top
    ch = asc - top + desc + 1
    cw = size
    n = LAST - FIRST + 1
    rows = (n + COLS - 1) // COLS
    sheet = Image.new("RGBA", (COLS * cw, rows * ch), (0, 0, 0, 0))
    adv = []
    for i in range(n):
        c = chr(FIRST + i)
        cell = Image.new("RGBA", (cw, ch), (0, 0, 0, 0))
        d = ImageDraw.Draw(cell)
        d.fontmode = "1"
        d.text((0, -top), c, font=ft, fill=(255, 255, 255, 255))
        sheet.paste(cell, ((i % COLS) * cw, (i // COLS) * ch))
        adv.append(int(round(ft.getlength(c))))
    write_sprite(name, [sheet], 0, 0)
    return dict(name=name, cw=cw, ch=ch, cap=cap, adv=adv)


ui = bake("spr_font_ui", 20)
big = bake("spr_font_big", 40)


def struct(f):
    return "{ spr: %s, cw: %d, ch: %d, cap: %d, adv: [%s] }" % (f["name"], f["cw"], f["ch"], f["cap"], ", ".join(str(a) for a in f["adv"]))


gml = '''// scr_font: the game's pixel font (Jersey 10, SIL Open Font License; see art_source/fonts). GENERATED by tools/build_font.py.
// Text is drawn glyph by glyph from a sprite atlas so it stays on whole pixels and is proportional. Two sizes: UI (20 px) and
// big (40 px, for titles). Alignment follows draw_set_halign / draw_set_valign; vertical middle is the middle of the capitals.

#macro FONT_FIRST  32
#macro FONT_COLS   16

function font_setup() {
    global.fonts = {
        ui:  %s,
        big: %s
    };
}

function font_get(_big) {
    if (!variable_global_exists("fonts")) font_setup();
    return _big ? global.fonts.big : global.fonts.ui;
}

/// @desc Width in GUI pixels of a string at scale _s.
function ui_text_w(_str, _big = false, _s = 1) {
    var _f = font_get(_big);
    var _w = 0;
    var _n = string_length(_str);
    for (var i = 1; i <= _n; i++) {
        var _g = ord(string_char_at(_str, i)) - FONT_FIRST;
        if (_g < 0 || _g >= array_length(_f.adv)) _g = ord("?") - FONT_FIRST;
        _w += _f.adv[_g];
    }
    return _w * _s;
}

/// @desc Draws a string in the current colour and alpha. Single line.
function ui_text(_x, _y, _str, _big = false, _s = 1) {
    var _f = font_get(_big);
    var _ha = draw_get_halign();
    var _va = draw_get_valign();
    var _w = ui_text_w(_str, _big, _s);
    if (_ha == fa_center) _x -= _w / 2;
    else if (_ha == fa_right) _x -= _w;
    if (_va == fa_middle) _y -= _f.cap * _s / 2;
    else if (_va == fa_bottom) _y -= _f.cap * _s;
    _x = floor(_x);
    _y = floor(_y);
    var _col = draw_get_colour();
    var _al = draw_get_alpha();
    var _n = string_length(_str);
    for (var i = 1; i <= _n; i++) {
        var _g = ord(string_char_at(_str, i)) - FONT_FIRST;
        if (_g < 0 || _g >= array_length(_f.adv)) _g = ord("?") - FONT_FIRST;
        if (_g > 0) {
            draw_sprite_part_ext(_f.spr, 0, (_g mod FONT_COLS) * _f.cw, (_g div FONT_COLS) * _f.ch, _f.cw, _f.ch, _x, _y, _s, _s, _col, _al);
        }
        _x += _f.adv[_g] * _s;
    }
}

/// @desc Text with a dark drop shadow, in the current colour.
function ui_text_shadow(_x, _y, _str, _big = false, _s = 1) {
    var _c = draw_get_colour();
    draw_set_colour(make_colour_rgb(8, 6, 14));
    ui_text(_x + _s * 2, _y + _s * 2, _str, _big, _s);
    draw_set_colour(_c);
    ui_text(_x, _y, _str, _big, _s);
}
''' % (struct(ui), struct(big))
open(os.path.join(ROOT, "tools", "gml", "scr_font.gml"), "w", encoding="utf8", newline="\n").write(gml)
print("font baked", ui["cap"], ui["ch"], big["cap"], big["ch"])
